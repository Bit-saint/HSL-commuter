import Foundation
import Observation
import ETAEngine
import HSLKit

/// App-wide state: settings, saved commutes and shared services.
@MainActor
@Observable
final class AppModel {
    // MARK: Settings (persisted)

    var apiKey: String { didSet { save() } }
    /// Personal walking speed, m/s. Calibrated automatically while walking during commutes.
    var walkingSpeed: Double { didSet { save() } }
    /// Extra seconds to be at the stop on top of the mode default.
    var extraBuffer: Double { didSet { save() } }
    /// Home, work and working hours. Drives the two daily commutes.
    var homeWork: HomeWorkSetup { didSet { save() } }
    /// Extra commutes (gym, school…), in addition to home ↔ work.
    var commutes: [Commute] { didSet { save() } }
    var hasCompletedSetup: Bool { didSet { save() } }
    var smart: SmartSettings { didSet { save(); smartSettingsChanged(from: oldValue) } }
    /// Save each live commute so it can be replayed later (Settings › Demo).
    var recordTrips: Bool { didSet { save() } }
    /// Launched with -demo (CI screenshots): skip setup and play the sample trip.
    let isDemoLaunch = ProcessInfo.processInfo.arguments.contains("-demo")

    // MARK: Live context

    /// Current weather and what it means for walking (FMI forecast).
    var weather: WeatherConditions?
    var weatherImpact: WeatherImpact {
        guard smart.weatherAware, let weather else { return .neutral }
        return WeatherImpact.assess(weather)
    }
    /// Your walking speed adjusted for today's weather.
    var effectiveWalkingSpeed: Double { walkingSpeed * weatherImpact.walkingFactor }
    /// Margin at the stop, including weather.
    var effectiveBuffer: Double { extraBuffer + weatherImpact.extraBuffer }
    /// Latest HSL alerts (refreshed every few minutes while the app runs).
    var alerts: [ServiceAlert] = []
    @ObservationIgnored private var alertsFetchedAt = Date.distantPast
    @ObservationIgnored private var weatherFetchedAt = Date.distantPast

    // MARK: Services

    let location = LocationService()
    let walking = WalkingRouter()
    let notifications = NotificationService()
    let liveActivity = LiveActivityController()
    let cues = CueSpeaker()
    let motion = MotionService()
    let calendarService = CalendarService()
    let places = PlaceLearningService()
    let autoStart = AutoStartMonitor()
    let crowd = CrowdReportService()
    /// Indoor station layouts (generated by tools/stations/build_stations.py).
    let stations: StationMap = AppModel.loadStations()
    let learnedSegments: LearnedSegmentStore

    /// The running live commute, if any.
    var session: CommuteSession?

    var client: DigitransitClient { DigitransitClient(apiKey: apiKey) }

    private let defaults = UserDefaults.standard

    init() {
        let bundledKey = Bundle.main.object(forInfoDictionaryKey: "DigitransitAPIKey") as? String ?? ""
        apiKey = defaults.string(forKey: "apiKey") ?? (bundledKey.hasPrefix("$(") ? "" : bundledKey)
        walkingSpeed = defaults.object(forKey: "walkingSpeed") as? Double ?? 1.35
        extraBuffer = defaults.object(forKey: "extraBuffer") as? Double ?? 0
        hasCompletedSetup = defaults.bool(forKey: "hasCompletedSetup")
        recordTrips = defaults.bool(forKey: "recordTrips")
        if let data = defaults.data(forKey: "homeWork"), let hw = try? JSONDecoder().decode(HomeWorkSetup.self, from: data) {
            homeWork = hw
        } else {
            homeWork = HomeWorkSetup()
        }
        if let data = defaults.data(forKey: "commutes"), let list = try? JSONDecoder().decode([Commute].self, from: data) {
            commutes = list
        } else {
            commutes = []
        }
        if let data = defaults.data(forKey: "smart"), let s = try? JSONDecoder().decode(SmartSettings.self, from: data) {
            smart = s
        } else {
            smart = SmartSettings()
        }
        learnedSegments = Persistence.loadLearnedSegments()
    }

    private static func loadStations() -> StationMap {
        guard let url = Bundle.main.url(forResource: "stations", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let map = try? StationMap.decode(data) else {
            return StationMap(version: 1, generated: nil, attribution: nil, stations: [])
        }
        return map
    }

    /// Call once at launch (also on background relaunches for geofence/visit events).
    func bootstrap() {
        // Lock Screen "how full?" buttons land here.
        ReportOccupancyIntent.handler = { level in
            AppModel.shared.session?.answerOccupancy(CrowdLevel(rawValue: level) ?? .standing)
        }
        if isDemoLaunch {
            // -demo [-demoSpeed 10]: straight into the sample trip, no setup, no learning.
            let args = ProcessInfo.processInfo.arguments
            let speed = args.firstIndex(of: "-demoSpeed").flatMap { args.indices.contains($0 + 1) ? Double(args[$0 + 1]) : nil }
            startDemo(speed: speed ?? 10)
            return
        }
        if smart.learnPlaces { places.start(app: self) }
        Task { await autoStart.configure(app: self) }
    }

    private func smartSettingsChanged(from old: SmartSettings) {
        if old.learnPlaces != smart.learnPlaces {
            if smart.learnPlaces { places.start(app: self) } else { places.stop() }
        }
        if old.autoStart != smart.autoStart { Task { await autoStart.configure(app: self) } }
        if smart.useCalendar && !old.useCalendar { Task { await calendarService.requestAccess() } }
    }

    private func save() {
        defaults.set(apiKey, forKey: "apiKey")
        defaults.set(walkingSpeed, forKey: "walkingSpeed")
        defaults.set(extraBuffer, forKey: "extraBuffer")
        defaults.set(hasCompletedSetup, forKey: "hasCompletedSetup")
        defaults.set(recordTrips, forKey: "recordTrips")
        if let data = try? JSONEncoder().encode(commutes) { defaults.set(data, forKey: "commutes") }
        if let data = try? JSONEncoder().encode(homeWork) { defaults.set(data, forKey: "homeWork") }
        if let data = try? JSONEncoder().encode(smart) { defaults.set(data, forKey: "smart") }
    }

    func persistLearning() {
        Persistence.save(learnedSegments)
    }

    /// Home ↔ work for the given day (with that day's times) followed by the extra commutes.
    /// With the calendar on, an early first meeting moves the arrive-by time earlier.
    func allCommutes(on date: Date = Date()) -> [Commute] {
        var hw = homeWork.commutes(on: date)
        if smart.useCalendar, hw.count == 2, let arrive = hw[0].arriveByMinutes,
           let meeting = calendarService.firstMeetingMinutes(on: date, before: arrive + 60), meeting - 10 < arrive {
            hw[0].arriveByMinutes = max(meeting - 10, 0)
        }
        return hw + commutes
    }

    /// Is this a commute day? Weekends, Finnish holidays, working-from-home and calendar days off are not.
    func dayStatus(on date: Date = Date()) -> DayStatus {
        let weekday = Calendar.current.component(.weekday, from: date)
        if smart.holidayAware, let h = FinnishCalendar.holiday(on: date) {
            return .dayOff(reason: loc(h.name), symbol: "sparkles")
        }
        if homeWork.wfhDays.contains(FinnishCalendar.dayKey(date)) {
            return .dayOff(reason: String(localized: "Working from home"), symbol: "house.fill")
        }
        if !homeWork.workdays.contains(weekday) {
            return .dayOff(reason: String(localized: "Not a workday"), symbol: "sun.max.fill")
        }
        if smart.useCalendar, let title = calendarService.dayOffEvent(on: date) {
            return .dayOff(reason: title, symbol: "calendar")
        }
        return .workday
    }

    func setWorkingFromHome(_ on: Bool, date: Date = Date()) {
        let key = FinnishCalendar.dayKey(date)
        if on { homeWork.wfhDays.insert(key) } else { homeWork.wfhDays.remove(key) }
        // Keep the set small.
        let cutoff = FinnishCalendar.dayKey(date.addingTimeInterval(-7 * 86_400))
        homeWork.wfhDays = homeWork.wfhDays.filter { $0 >= cutoff }
        Task { await LeaveReminderScheduler.refresh(app: self) }
    }

    func refreshWeather(near point: GeoPoint? = nil) async {
        guard smart.weatherAware, Date().timeIntervalSince(weatherFetchedAt) > 15 * 60 else { return }
        guard let p = point ?? location.current ?? homeWork.home?.point else { return }
        weatherFetchedAt = Date()
        weather = try? await FMIWeatherClient().conditions(at: p)
    }

    func refreshAlerts() async {
        guard Date().timeIntervalSince(alertsFetchedAt) > 120, !apiKey.isEmpty else { return }
        alertsFetchedAt = Date()
        if let list = try? await client.alerts() { alerts = list }
    }

    /// The commute that makes sense right now: to work in the morning, home after the
    /// middle of the working day. Falls back to the first extra commute.
    func suggestedCommute(now: Date = Date()) -> Commute? {
        let hw = homeWork.commutes(on: now)
        if hw.count == 2 { return homeWork.isMorning(now) ? hw[0] : hw[1] }
        guard let first = commutes.first(where: { $0.isActive(on: now) }) ?? commutes.first else { return nil }
        let hour = Calendar.current.component(.hour, from: now)
        return hour < 12 ? first : first.reversed
    }

    /// The opposite direction: to work ↔ to home keep their own times.
    func counterpart(of commute: Commute, now: Date = Date()) -> Commute {
        let hw = homeWork.commutes(on: now)
        if hw.count == 2 {
            if commute.id == HomeWorkSetup.toWorkID { return hw[1] }
            if commute.id == HomeWorkSetup.toHomeID { return hw[0] }
        }
        return commute.reversed
    }

    // MARK: Live sessions

    func startSession(itinerary: Itinerary, destinationName: String, automatic: Bool = false) {
        session?.stop()
        let s = CommuteSession(itinerary: itinerary, destinationName: destinationName, app: self, automatic: automatic)
        session = s
        Task { await s.start() }
    }

    /// Replays a recorded trip (the bundled sample if none is given) as if it were happening now.
    func startDemo(_ recording: TripRecording? = nil, speed: Double = 10) {
        guard let rec = recording ?? TripRecorder.sample else { return }
        session?.stop()
        let replay = TripReplay(recording: rec, speed: speed)
        let s = CommuteSession(itinerary: rec.itinerary, destinationName: rec.destinationName, app: self, replay: replay)
        session = s
        Task { await s.start() }
    }

    func stopSession() {
        session?.stop()
        session = nil
        persistLearning()
    }

    /// After a miss: plan again from where the user is now to the same destination.
    func replan() async {
        guard let current = session, let destination = current.itinerary.legs.last?.to.location else { return }
        let origin = await location.currentLocation().map { GeoPoint($0.coordinate) }
            ?? current.itinerary.legs.first?.from.location
        guard let origin,
              let itineraries = try? await client.plan(from: origin, to: destination, count: 4, walkSpeed: effectiveWalkingSpeed),
              let best = itineraries.map({ Planner.option(for: $0, app: self) })
                .first(where: { $0.leaveAt > Date().addingTimeInterval(-60) }) else { return }
        startSession(itinerary: best.itinerary, destinationName: current.destinationName)
    }

    /// Track a single departure picked from a stop board.
    func track(departure: Departure, at stop: StopRef) {
        let leg = Leg(mode: departure.route.mode, scheduledStart: departure.scheduled, scheduledEnd: departure.scheduled,
                      estimatedStart: departure.realtime, estimatedEnd: nil, distance: 0,
                      from: Place(name: stop.name, location: stop.location, stop: stop),
                      to: Place(name: departure.headsign, location: stop.location, stop: nil),
                      geometry: [], route: departure.route,
                      trip: TripRef(tripId: departure.tripId, directionId: departure.directionId,
                                    serviceDate: departure.serviceDate, headsign: departure.headsign),
                      headsign: departure.headsign, isRealtime: departure.isRealtime)
        let itinerary = Itinerary(start: departure.realtime, end: departure.realtime, legs: [leg], walkDistance: 0)
        startSession(itinerary: itinerary, destinationName: departure.headsign)
    }

    /// Nudges the personal walking speed towards an observed one.
    func observeWalkingSpeed(_ v: Double) {
        // Undo today's weather slowdown so icy days don't teach us you're a slow walker.
        let normalized = v / weatherImpact.walkingFactor
        guard (0.7...2.3).contains(normalized) else { return }
        walkingSpeed = walkingSpeed * 0.98 + normalized * 0.02
    }
}

enum Persistence {
    static var learnedURL: URL {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("learned-segments.json")
    }

    static func loadLearnedSegments() -> LearnedSegmentStore {
        guard let data = try? Data(contentsOf: learnedURL),
              let store = try? JSONDecoder().decode(LearnedSegmentStore.self, from: data) else {
            return LearnedSegmentStore()
        }
        return store
    }

    static func save(_ store: LearnedSegmentStore) {
        if let data = try? JSONEncoder().encode(store) {
            try? data.write(to: learnedURL, options: .atomic)
        }
    }
}
